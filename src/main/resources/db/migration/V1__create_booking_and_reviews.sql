-- Initial schema for NEW installations. Existing databases require an inspected baseline.
CREATE TABLE booking (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name varchar(255),
    passenger_count integer,
    pick_up_location varchar(255),
    drop_off_location varchar(255),
    transfer_date_time timestamp(6),
    return_date_time timestamp(6),
    price numeric(38,2),
    phone_number varchar(255),
    email varchar(255),
    country_of_residence varchar(255),
    transfer_address varchar(255),
    hotel_name varchar(120),
    special_requests varchar(2000),
    flight_number varchar(20),
    luggage_count integer,
    baby_seat_count integer,
    vehicle_id varchar(255),
    trip_type varchar(255),
    status varchar(255),
    created_at timestamp(6) with time zone,
    idempotency_key varchar(64) UNIQUE,
    request_fingerprint varchar(255)
);
CREATE INDEX idx_booking_status_transfer_time ON booking (status, transfer_date_time);
CREATE INDEX idx_booking_transfer_time ON booking (transfer_date_time);

CREATE TABLE customer_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name varchar(80) NOT NULL,
    rating integer NOT NULL,
    comment varchar(1500) NOT NULL,
    status varchar(16) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);
