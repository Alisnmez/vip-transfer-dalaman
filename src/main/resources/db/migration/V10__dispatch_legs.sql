CREATE TABLE IF NOT EXISTS dispatch_leg (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking(id),
    leg varchar(255) NOT NULL,
    driver varchar(255), phone varchar(255), plate varchar(255), capacity integer,
    stage varchar(255), assigned_at timestamp with time zone, reviewed_at timestamp with time zone,
    verified_at timestamp with time zone, reviewed_priority integer,
    revision integer NOT NULL DEFAULT 0,
    UNIQUE (booking_id, leg)
);
CREATE TABLE IF NOT EXISTS dispatch_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking(id),
    leg varchar(255) NOT NULL, description varchar(255) NOT NULL, occurred_at timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_dispatch_activity_booking ON dispatch_activity(booking_id,id);
