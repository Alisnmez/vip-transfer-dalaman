CREATE TABLE booking_management_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking(id),
    request_type varchar(16) NOT NULL CHECK (request_type IN ('CHANGE', 'CANCEL')),
    message varchar(2000) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'IN_PROGRESS', 'RESOLVED', 'DECLINED')),
    admin_note varchar(2000),
    idempotency_key varchar(64) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE INDEX idx_management_request_status_created
    ON booking_management_request (status, created_at DESC);
CREATE INDEX idx_management_request_booking
    ON booking_management_request (booking_id, created_at DESC);
